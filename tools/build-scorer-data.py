"""Regenerates the character tables in crates/typomend-scorer/data.

readings.txt  Mandarin readings of the 5401 common characters of Big5 level 1 and
              the 8105 of the Table of General Standard Chinese Characters, from
              Unihan kMandarin, kHanyuPinlu and kTGHZ2013, as toned pinyin such as
              wen4, tagged with the script they are common in. These drive the
              homophone candidate generator.
t2s.txt       Simplified forms of Traditional characters from OpenCC
              TSCharacters.txt, the most common first, as OpenCC lists them.
              Only single characters are kept, so converting text never
              changes its length.

Usage: python tools/build-scorer-data.py <Unihan dir> <TSCharacters.txt>
Pass - as the Unihan directory to regenerate t2s.txt alone.
Unihan: https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip
OpenCC: https://github.com/BYVoid/OpenCC/blob/master/data/dictionary/TSCharacters.txt
"""

import re
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates" / "typomend-scorer" / "data"

TONE_MARKS = {"̄": 1, "́": 2, "̌": 3, "̀": 4}


def numbered(syllable: str) -> str:
    """Turns wèn into wen4 and ü into v; a neutral tone gets 5."""
    tone = 5
    plain = []
    for c in unicodedata.normalize("NFD", syllable):
        if c in TONE_MARKS:
            tone = TONE_MARKS[c]
        elif c == "̈":
            plain[-1] = "v"
        else:
            plain.append(c)
    return "".join(plain) + str(tone)


def unihan(dir: Path, name: str, field: str) -> dict:
    """Returns the character to value map of one field of a Unihan file."""
    values = {}
    for line in (dir / name).read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) == 3 and parts[1] == field:
            values[chr(int(parts[0][2:], 16))] = parts[2]
    return values


def readings(dir: Path) -> None:
    """Writes readings.txt from the Unihan files in `dir`."""
    big5 = unihan(dir, "Unihan_OtherMappings.txt", "kBigFive")
    traditional = {
        c for c, code in big5.items() if 0xA440 <= int(code.split()[0][:4], 16) <= 0xC67E
    }
    # kTGHZ2013 lists the 8105 characters of the Table of General Standard
    # Chinese Characters with their readings: 381.170:wéi 383.210:wèi.
    tghz = unihan(dir, "Unihan_Readings.txt", "kTGHZ2013")
    simplified = set(tghz)
    mandarin = unihan(dir, "Unihan_Readings.txt", "kMandarin")
    pinlu = unihan(dir, "Unihan_Readings.txt", "kHanyuPinlu")
    lines = []
    for c in sorted(traditional | simplified):
        found = mandarin.get(c, "").split()
        # kHanyuPinlu lists readings with corpus counts: wèi(1234) wéi(56).
        found += re.findall(r"([^\s(]+)\(", pinlu.get(c, ""))
        found += re.findall(r":(\S+)", tghz.get(c, ""))
        syllables = list(dict.fromkeys(numbered(s) for s in found))
        if not syllables:
            continue
        # B: common in both scripts, T: Traditional only, S: Simplified only.
        script = "B" if c in traditional and c in simplified else "T" if c in traditional else "S"
        lines.append(f"{c}\t{script}\t{' '.join(syllables)}")
    write("readings.txt", "Unicode Unihan database (Unicode License v3)", lines)


def t2s(path: Path) -> None:
    """Writes t2s.txt from the OpenCC TSCharacters.txt at `path`."""
    lines = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or "\t" not in line:
            continue
        key, values = line.split("\t", 1)
        forms = [v for v in values.split() if len(v) == 1]
        if len(key) == 1 and any(f != key for f in forms):
            lines.append(f"{key}\t{' '.join(forms)}")
    write("t2s.txt", "OpenCC TSCharacters.txt (Apache License 2.0)", lines)


def write(name: str, source: str, lines: list) -> None:
    """Writes a table into OUT, headed by a comment naming its source."""
    OUT.mkdir(parents=True, exist_ok=True)
    header = f"# Generated by tools/build-scorer-data.py from {source}.\n"
    (OUT / name).write_text(header + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{name}: {len(lines)} entries")


def main() -> None:
    """Regenerates the tables named on the command line."""
    if sys.argv[1] != "-":
        readings(Path(sys.argv[1]))
    t2s(Path(sys.argv[2]))


if __name__ == "__main__":
    main()
